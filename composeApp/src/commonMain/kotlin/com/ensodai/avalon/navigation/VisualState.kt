package com.ensodai.avalon.navigation

/**
 * Стейт-машина жизненного цикла экрана в AvalonNavHost.
 * Гарантирует строгий порядок анимаций и рендеринга (кто рисуется, кто спит, кто участвует в параллаксе).
 */
enum class VisualState {
    /** Экран только что родился и прямо сейчас анимированно выезжает справа налево. */
    ENTERING,

    /**
     * Экран полностью выехал и находится на самом верху стека.
     * Только он перехватывает жесты "назад".
     */
    ACTIVE,

    /**
     * Экран находится прямо под `ACTIVE` (или под серией прозрачных слоев).
     * Участвует в эффекте "Параллакса", сдвигаясь на `PARALLAX_FACTOR` влево.
     */
    UNDERNEATH,

    /**
     * Любой экран ниже UNDERNEATH, который мы продолжаем держать в композиции.
     * Это убирает резкое "всплытие" глубинных экранов во время pop и делает
     * раскрытие стека плавным на любой глубине вложенности.
     *
     * В отличие от UNDERNEATH, экран не является главным носителем параллакса,
     * но уже присутствует в дереве UI и не появляется внезапно посреди анимации.
     */
    BACKGROUND,

    /**
     * Экран похоронен глубоко в стеке (индекс N-2 и глубже).
     * Жесткая оптимизация: он ВООБЩЕ не участвует в композиции и отрисовке (return@forEach).
     * Ждет, пока верхние экраны не закроют.
     */
    STASHED,

    /**
     * "ПРИЗРАК" 👻. Экран УЖЕ удален из логического `NavBackStack`, но визуально еще жив.
     * Он проигрывает анимацию отлета вправо. По завершении анимации он навсегда удаляется из памяти.
     */
    EXITING
}
