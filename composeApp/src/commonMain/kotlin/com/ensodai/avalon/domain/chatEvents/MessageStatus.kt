package com.ensodai.avalon.domain.chatEvents

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Определяет полный жизненный цикл исходящего сообщения на стороне клиента.
 *
 * Этот класс — "источник правды" для UI. Основываясь на этих статусах,
 * интерфейс показывает пользователю, что происходит с его сообщением:
 * отправляется ли оно, доставлено, или произошла ошибка.
 *
 * Жизненный цикл выглядит так:
 *
 * PENDING -> (опционально SENDING) -> SENT
 *                                   |
 *                                   -> FAILED
 */
@Serializable
sealed class MessageStatus {

    /**
     * **"В очереди на отправку"**
     *
     * Начальный статус для любого нового сообщения.
     *
     * - **Когда используется:** Устанавливается сразу после того, как пользователь нажал кнопку "Отправить".
     *   Сообщение уже сохранено в локальную базу данных, но еще не передано в сеть.
     *   Оно ждёт своей очереди в `RateLimitedSender`.
     *
     * - **Как выглядит в UI:** Обычно иконка "часики" 🕘.
     */
    @Serializable
    @SerialName("PENDING")
    object PENDING : MessageStatus()

    /**
     * **"Отправляется"**
     *
     * Промежуточный статус, который показывает, что сообщение в данный момент
     * активно передаётся по сети.
     *
     * - **Когда используется (опционально, но полезно):** Этот статус можно установить
     *   непосредственно перед вызовом `session.send()` в `WebSocketManager`.
     *   Он показывает, что сообщение покинуло очередь и летит на сервер.
     *
     * - **Как выглядит в UI:** Тоже иконка "часики" 🕘. Для пользователя разница
     *   между `PENDING` и `SENDING` может быть незаметна, но для отладки это полезно.
     */
    @Serializable
    @SerialName("SENDING")
    object SENDING : MessageStatus()

    /**
     * **"Доставлено на сервер"**
     *
     * Финальный успешный статус. Сообщение гарантированно находится на сервере.
     *
     * - **Когда используется:** Устанавливается, когда от сервера приходит
     *   подтверждение `ServerMessage.MessageAck`. Клиент находит сообщение
     *   в своей базе по `clientId` и обновляет его статус на `SENT`.
     *
     * - **Как выглядит в UI:** "Одна галочка" ✅.
     */
    @Serializable
    @SerialName("SENT")
    object SENT : MessageStatus()

    /**
     * **"Ошибка отправки"**
     *
     * Финальный статус, если доставить сообщение не удалось.
     *
     * - **Когда используется:** Устанавливается в двух случаях:
     *   1. От сервера пришло сообщение `ServerMessage.MessageError`.
     *   2. (В будущем) Если `WebSocketManager` не смог доставить сообщение после
     *      нескольких попыток переподключения (если вы решите добавить такой лимит).
     *
     * - **Как выглядит в UI:** Красный восклицательный знак ❗️. Пользователю
     *   можно дать возможность нажать на него, чтобы попробовать отправить снова.
     *
     * @param reason Машиночитаемая причина ошибки, полученная от сервера
     *               (например, "chat_not_found"). Полезна для отладки и
     *               отображения осмысленных сообщений об ошибках.
     */
    @Serializable
    @SerialName("FAILED")
    data class FAILED(val reason: String) : MessageStatus()
}
