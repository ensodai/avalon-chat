package com.ensodai.avalon.navigation

import androidx.compose.animation.core.CubicBezierEasing
import kotlin.math.abs
import kotlin.math.max

/**
 * Набор кастомных кривых Безье (Easings), отвечающих за "характер" анимаций.
 * В отличие от стандартных Material-кривых (FastOutSlowIn и др.), эти кривые
 * обеспечивают фирменную плавность и отзывчивость, характерную для Telegram.
 */
object TelegramEasings {
    /**
     * Тот самый [CubicBezierInterpolator.DEFAULT] из исходников Telegram.
     * Используется для стандартных появлений и возвратов на место.
     * Дает быстрый старт, но очень мягкое, "шелковое" торможение в конце.
     */
    val Default = CubicBezierEasing(0.25f, 0.1f, 0.25f, 1f)

    /**
     * Экстремально быстрая кривая затухания (Ease-Out-Quint).
     * Применяется ИСКЛЮЧИТЕЛЬНО для отлетов экрана (закрытия).
     * Когда юзер смахивает экран, он хочет, чтобы тот исчез мгновенно, не мозоля глаза.
     * Эта кривая выстреливает экран за пределы видимости почти моментально.
     */
    val EaseOutQuint = CubicBezierEasing(0.23f, 1f, 0.32f, 1f)
}

/**
 * Конфигурация физики, порогов срабатывания и таймингов для системы навигации.
 * Большинство значений откалиброваны на основе `ActionBarLayout.java`
 * и `BottomSheet.java` из открытого исходного кода Telegram.
 */
object AvalonTransitions {
    // ====================================================================
    // 🎨 ВИЗУАЛЬНЫЕ КОНСТАНТЫ
    // ====================================================================

    /**
     * Коэффициент параллакса (0.1 = 10%).
     * Насколько сильно нижний экран сдвинут влево, когда верхний экран полностью открыт.
     * Значение 0.3f (30%) делало анимацию слишком "тяжелой", 10% — идеальный баланс глубины.
     */
    const val PARALLAX_FACTOR = 0.0f

    /** Порог прохождения дистанции (1/3 экрана), после которого жест считается успешным, если нет резкого флинга. */
    const val SWIPE_THRESHOLD = 0.333f

    // ====================================================================
    // ⚡ ФИЗИКА И ВЕКТОРЫ СКОРОСТИ
    // ====================================================================

    /** Порог скорости для уверенного броска вправо (закрытие экрана). */
    const val FORWARD_FLING_VELOCITY = 500f

    /** Порог скорости броска влево, при котором юзер ОСОЗНАННО отменяет закрытие и возвращает экран. */
    const val CANCEL_FLING_VELOCITY = -1000f

    /** Максимальная учитываемая скорость. Все, что быстрее, обрезается, чтобы анимация не ломалась (не уходила в 0 мс). */
    const val MAX_VELOCITY = 3500f

    // ====================================================================
    // ✋ ЭРГОНОМИКА ТАЧА (SLOP & DEAD ZONES)
    // ====================================================================

    /**
     * 🔥 "Зона свободы" (Touch Slop).
     * Расстояние, которое палец должен пройти по экрану, прежде чем UI начнет двигаться.
     * Защищает от ложных свайпов (например, когда юзер просто тапает по экрану, но палец чуть дрогнул).
     * В Telegram используется ~0.4 см (~25dp). 20dp — отличный баланс отзывчивости и защиты.
     */
    const val TOUCH_DELAY_DP = 20f

    /** Ширина активной зоны у левого края экрана, где перехватчик работает в режиме "Диктатора" (PointerEventPass.Initial). */
    const val EDGE_SWIPE_ZONE_DP = 30f

    /** Базовая длительность анимации, если экран движется от края до края с нулевой начальной скоростью. */
    const val BASE_DURATION_MS = 300

    // ====================================================================
    // 🧮 ВЫСШАЯ МАТЕМАТИКА АНИМАЦИИ
    // ====================================================================

    /**
     * Динамический расчет времени анимации на основе закона сохранения импульса.
     * Если юзер бросил экран на середине с огромной скоростью, нельзя анимировать остаток пути
     * за базовые 300мс — экран визуально "ударится о невидимую стену" и замедлится.
     * Время должно пропорционально сокращаться!
     *
     * @param currentOffset Текущее смещение экрана в пикселях.
     * @param screenWidth Общая ширина экрана.
     * @param velocity Мгновенная скорость пальца в момент отрыва.
     * @param isPopping Направление (true — экран улетает вправо/закрывается, false — возвращается на 0).
     * @return Длительность анимации в миллисекундах.
     */
    fun calculateTelegramDuration(
        currentOffset: Float,
        screenWidth: Float,
        velocity: Float,
        isPopping: Boolean
    ): Int {
        val progress = currentOffset / screenWidth

        // Сколько % пути осталось пройти анимации (до края экрана при закрытии, или до 0 при возврате)
        val distanceFraction = if (isPopping) 1f - progress else progress

        // Влияние скорости: нормализуем от 0 до 1
        val velocityFactor = (abs(velocity) / MAX_VELOCITY).coerceIn(0f, 1f)

        // 🔥 Ядро формулы:
        // 1. Берем базовое время (300мс).
        // 2. Умножаем на оставшуюся дистанцию (если осталось 50% пути -> время падает).
        // 3. Вычитаем бонус за скорость (до 20% от времени).
        // 4. Ограничиваем нижний порог коэффицента (0.4f), чтобы экран не телепортировался быстрее чем за 120мс.
        val timeAdjusted = BASE_DURATION_MS * max(0.4f, distanceFraction - 0.2f * velocityFactor)

        // Хард-лимиты: анимация никогда не должна быть быстрее 150мс (человеческий глаз не воспримет плавно)
        // и медленнее 300мс (слишком вяло).
        return timeAdjusted.toInt().coerceIn(150, BASE_DURATION_MS)
    }
}
