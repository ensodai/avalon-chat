package com.ensodai.avalon.navigation

/**
 * Описание фаз текущего жеста навигации.
 * Полезно для синхронизации вложенного UI (например, скрытия FAB'ов во время свайпа).
 */
enum class SwipeBackPhase {
    /** Жест не активен. Экран полностью открыт или полностью закрыт. */
    Idle,

    /** Пользователь прямо сейчас тянет экран пальцем. */
    Dragging,

    /**
     * Пользователь отпустил палец (отмена жеста).
     * Экран анимированно возвращается в нулевую координату (левый край).
     */
    SnappingBack,

    /**
     * Жест был успешен (пройден порог или совершен резкий флинг).
     * Экран анимированно улетает вправо за пределы видимости.
     */
    Completing
}
