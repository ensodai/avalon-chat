    /**
     * Возвращает каскад эмодзи для анимации
     */
    fun getCascade(trigger: String?): List<String> {
        return cascades[trigger] ?: defaultCascade
    }

    /**
     * Валидирует реакцию для бека:
     * - null → null
     * - если есть в cascades → вернуть как есть
     * - иначе → дефолтное эмодзи "👍"
     */
    fun validateReaction(reaction: String?): String? {
        return when {
            reaction == null -> null
            cascades.containsKey(reaction) -> reaction
            else -> "👍"
        }
    }

    /**
     * Возвращает набор доступных ключей-реакций для отображения в UI.
     * Ключи — это основные эмодзи из cascades.
     */
