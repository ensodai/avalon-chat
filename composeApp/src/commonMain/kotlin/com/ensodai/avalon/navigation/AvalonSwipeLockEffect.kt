package com.ensodai.avalon.navigation

import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect

/**
 * Утилитарный Composable-эффект для динамической блокировки жеста "свайп назад" (Swipe-to-Pop).
 *
 * Позволяет любому дочернему компоненту временно запретить закрытие экрана жестом.
 * Это критически важно для экранов со сложным внутренним взаимодействием, где горизонтальный
 * свайп должен обрабатываться самим контентом, а не системой навигации.
 *
 * 🔥 Частые Use-Cases:
 * - Экраны с картами (Google Maps / Yandex Maps), где юзер панорамирует карту пальцем.
 * - Канвас для рисования (где свайп от левого края — это штрих кистью).
 * - Полноэкранные просмотрщики фото (Image Pager) с зумом и панорамированием.
 * - Важные формы ввода, где мы хотим защитить юзера от случайного закрытия экрана
 *   (свайп заблокирован, а по кнопке "Назад" показываем диалог "Сохранить черновик?").
 *
 * @param locked Если `true` — жест закрытия от края блокируется. Если `false` — разрешается.
 */
@Composable
fun AvalonSwipeLockEffect(locked: Boolean = true) {
    // Получаем контекст текущего экрана. Если его нет (мы не внутри AvalonNavHost),
    // просто игнорируем (fail-safe поведение).
    val context = LocalAvalonSwipeContext.current ?: return

    // Используем DisposableEffect, привязанный к флагу locked.
    // Это гарантирует, что логика блокировки будет строго синхронизирована
    // с жизненным циклом вызывающего компонента.
    DisposableEffect(locked) {

        // 1. Применяем блокировку к физической модели экрана.
        // Это мгновенно отключит Modifier.swipeBack в AvalonNavHost.
        context.entry.isSwipeEnabled = !locked

        // 2. Гарантированная очистка (Safety Net).
        onDispose {
            // Срабатывает в двух случаях:
            // А) Флаг locked изменился с true на false (юзер закончил рисовать).
            // Б) Composable, вызвавший этот эффект, был удален из дерева (экран закрыли кнопкой).
            //
            // Мы ОБЯЗАНЫ вернуть isSwipeEnabled = true, иначе если стейт переиспользуется,
            // экран может остаться навсегда "застрявшим" без возможности свайпа.
            context.entry.isSwipeEnabled = true
        }
    }
}
